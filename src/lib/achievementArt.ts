/*
 * The art on every achievement card: one icon each, drawn as a stained-glass
 * enamel pin (components/PinArt.tsx), with an enamel colour that suits it
 * (water blue, fire orange, plants green). Card ids are stored, so this is
 * keyed by them; a new ladder needs six icons here (the unit test checks).
 * The catalog's emoji stay for the profile shared with a Compete partner, so
 * a partner on an older app still sees art.
 */

