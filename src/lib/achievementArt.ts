const FALLBACK: Art = [Sparkles, 'ivory'];

/** A card's art from its id: `<ladder>.<step>` or `secret.<key>`. */
export function artOf(id: string): CardArt {
  let a: Art | undefined;
  if (id.startsWith('secret.')) a = SECRET_ART[id.slice(7) as SecretKey];
  else {
    const dot = id.lastIndexOf('.');
    a = LADDER_ART[id.slice(0, dot)]?.[Number(id.slice(dot + 1)) - 1];
  }
  const [icon, ink] = a ?? FALLBACK;
  return { icon, ink };
}

/** Whether a card has art of its own (for the unit test). */
export function hasArt(id: string): boolean {
  if (id.startsWith('secret.')) return id.slice(7) in SECRET_ART;
  const dot = id.lastIndexOf('.');
  return !!LADDER_ART[id.slice(0, dot)]?.[Number(id.slice(dot + 1)) - 1];
}

